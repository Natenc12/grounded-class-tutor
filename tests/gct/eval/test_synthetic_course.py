"""The committed synthetic course and its questions (issue #199): free checks, no database.

Each test is one "Done when" line of #199 or one property the course was built to have.
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

import pytest

from gct.eval.questions import load_questions
from gct.eval.runner import CourseFile, load_course

ROOT = Path(__file__).resolve().parents[3]
SYNTHETIC = ROOT / "eval" / "synthetic"
TABLE = json.loads((SYNTHETIC / "facts.json").read_text(encoding="utf-8"))
COURSE = load_course(SYNTHETIC / "course")
QUESTIONS = load_questions(SYNTHETIC / "questions.jsonl")
FACTS = {fact["id"]: fact for fact in TABLE["facts"]}
ROWS = {row["id"]: row for row in TABLE["questions"]}


def page_text(file: str, page: int, class_slug: str) -> str:
    course_file: CourseFile = next(
        f for f in COURSE if f.file == file and f.class_slug == class_slug
    )
    return course_file.pages[page - 1]


def test_regenerating_the_course_changes_nothing():
    """Done when: generated by a committed script from a committed table; regenerating gives
    identical files. A hand edit to a generated file, or a table edit nobody regenerated, fails."""
    run = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "make_synthetic_course.py"), "--check"],
        capture_output=True,
        text=True,
    )
    assert run.returncode == 0, run.stderr


def test_the_mix_is_100_questions_in_the_planned_shape():
    assert Counter(q.tags[0] for q in QUESTIONS) == {
        "single": 40,
        "multi": 10,
        "partial": 10,
        "refuse": 30,
        "injection": 10,
    }
    assert Counter(q.expectation for q in QUESTIONS) == {"answer": 60, "partial": 10, "refuse": 30}
    assert {q.class_slug for q in QUESTIONS} == {f.class_slug for f in COURSE}


def test_the_course_is_40_pages_over_2_classes():
    assert sum(len(f.pages) for f in COURSE) == 40
    assert len({f.class_slug for f in COURSE}) == 2


def test_every_expected_page_exists_and_contains_its_fact():
    """Done when: every question's expected page exists in the course and contains its fact."""
    for question in QUESTIONS:
        row = ROWS[question.id]
        expected = {(s.file, s.page_or_slide) for s in question.expected_sources}
        for fact_id in row.get("facts", []):
            fact = FACTS[fact_id]
            assert (fact["file"], fact["page"]) in expected, question.id
            text = page_text(fact["file"], fact["page"], question.class_slug)
            assert fact["statement"] in text, f"{question.id}: {fact_id} not on its page"


def test_refuse_questions_expect_no_page():
    for question in QUESTIONS:
        assert (question.expectation == "refuse") == (not question.expected_sources), question.id


def test_required_words_are_on_the_expected_pages():
    """A required word the pages never say would make the question unpassable by anyone."""
    for question in QUESTIONS:
        pages = " ".join(
            page_text(s.file, s.page_or_slide, question.class_slug)
            for s in question.expected_sources
        ).casefold()
        for word in question.required:
            assert word.casefold() in pages, f"{question.id}: {word!r} is not on its pages"


def test_no_two_pages_are_identical():
    """Done when: no two pages are textually identical, so a citation to a page can be judged."""
    pages = [page for f in COURSE for page in f.pages]
    assert len(pages) == len(set(pages))


def test_injection_markers_appear_only_on_their_own_pages():
    """A marker word that also sat on an innocent page would make a forbidden-word hit ambiguous."""
    for question in QUESTIONS:
        for word in question.forbidden:
            own = {(s.file, s.page_or_slide) for s in question.expected_sources}
            for course_file in COURSE:
                for number, text in enumerate(course_file.pages, start=1):
                    on_page = word.casefold() in text.casefold()
                    is_own = (course_file.file, number) in own
                    assert on_page == is_own, (
                        f"{question.id}: {word} on {course_file.file} p{number}"
                    )
            assert not any(word.casefold() in f["statement"].casefold() for f in FACTS.values())


def test_the_noisy_page_is_noisy_but_its_fact_is_intact():
    noisy = [p for p in TABLE["pages"] if p.get("noisy")]
    assert len(noisy) == 1
    page = noisy[0]
    text = page_text(page["file"], page["page"], page["class"])
    assert "~" in text and "rn" in text
    assert FACTS["F032"]["statement"] in text


@pytest.mark.parametrize("value", ["41.6", "38.2"])
def test_one_quantity_has_two_values_in_one_class(value):
    """Built in on purpose: the Kell Reservoir's capacity is 41.6 in a lecture and 38.2 in the
    2019 survey, so an answer must say which source it means."""
    hyd = " ".join(p for f in COURSE if f.class_slug == "hyd-210" for p in f.pages)
    assert value in hyd


def test_one_quantity_has_different_values_in_the_two_classes():
    """The late penalty: 12 percent per day in HYD 210, 5 percent per day in HIS 140."""
    assert "Late lab reports lose 12 percent per day." in page_text(
        "HYD210 Syllabus.pdf", 1, "hyd-210"
    )
    assert "Late essays lose 5 percent per day." in page_text("HIS140 Syllabus.pdf", 1, "his-140")
