def question(qid: str, expectation: str, sources: list[tuple[str, int]]) -> EvalQuestion:
    return EvalQuestion(
        id=qid,
        question="q?",
        class_slug="c",
        expectation=expectation,
        expected_sources=[ExpectedSource(file=f, page_or_slide=p) for f, p in sources],
        answer_notes="",
        suites=["smoke"],
        tags=[],
        added="2026-01-01",
    )


class TestConvergeCorpus:
    """ "Every corpus file ingested exactly once" - the property that makes re-running safe."""

    def test_ingests_every_file_once_on_a_cold_class(self, db, corpus):
        conn, owner_id, class_id = db
        embedder = FakeEmbeddings()

        ready = ask_smoke._converge_corpus(
            conn, owner_id=owner_id, class_id=class_id, corpus_dir=corpus, embedder=embedder
        )

        assert sorted(ready) == ["alpha.pdf", "beta.pdf"]
        assert all(count > 0 for count in ready.values())
        assert embedder.calls, "a cold class must actually embed"

    def test_second_run_ingests_nothing_and_embeds_nothing(self, db, corpus):
        """THE anti-inflation property. `ingest_file` mints a fresh `file_id` every call and
        `index_file`'s idempotency is delete-by-file_id, so it can only ever replace a set WITHIN
        one file_id - never across runs. A runner that ingested unconditionally would add a
        complete duplicate chunk set on every run: the class doubles, retrieval fills its top-k
        with copies of one page, and every count printed goes with it.
        """
        conn, owner_id, class_id = db
        first = ask_smoke._converge_corpus(
            conn,
            owner_id=owner_id,
            class_id=class_id,
            corpus_dir=corpus,
            embedder=FakeEmbeddings(),
        )

        second_embedder = FakeEmbeddings()
        second = ask_smoke._converge_corpus(
            conn,
            owner_id=owner_id,
            class_id=class_id,
            corpus_dir=corpus,
            embedder=second_embedder,
        )

        assert second == first, "the census must not move on a re-run"
        assert second_embedder.calls == [], "a converged corpus must cost nothing to re-run"

    def test_empty_corpus_dir_is_a_setup_error(self, db, tmp_path):
        conn, owner_id, class_id = db
        empty = tmp_path / "empty"
        empty.mkdir()

        with pytest.raises(ask_smoke.SetupError, match="dogfood corpus is"):
            ask_smoke._converge_corpus(
                conn,
                owner_id=owner_id,
                class_id=class_id,
                corpus_dir=empty,
                embedder=FakeEmbeddings(),
            )

    def test_duplicate_ready_rows_warn_and_do_not_re_ingest(self, db, corpus, capsys):
        """The WARN branch, which the review found unexercised by everyone AND by the suite.

        It is the code added in response to a real incident (8 accumulated ingests of one deck),
        so leaving it unrun was exactly backwards. Duplicates must WARN, must NOT auto-delete
        (dropping chunk sets is not a bench's call), and must not re-ingest.
        """
        conn, owner_id, class_id = db
        ask_smoke._converge_corpus(
            conn,
            owner_id=owner_id,
            class_id=class_id,
            corpus_dir=corpus,
            embedder=FakeEmbeddings(),
        )
        # Ingest alpha.pdf a SECOND time - the real-world failure, reproduced exactly: a fresh
        # file_id, so the delete-by-file_id idempotency never fires.
        ingest_file(corpus / "alpha.pdf", owner_id, class_id, embedder=FakeEmbeddings(), conn=conn)

        embedder = FakeEmbeddings()
        ready = ask_smoke._converge_corpus(
            conn, owner_id=owner_id, class_id=class_id, corpus_dir=corpus, embedder=embedder
        )
        out = capsys.readouterr().out

        assert "WARN" in out and "alpha.pdf" in out
        assert "ingested more than once" in out
        assert "DUPLICATED" in out
        assert embedder.calls == [], "a duplicate must never trigger another ingest"
        # The reported count is the INFLATED total, and saying so is the point of the warning.
        assert ready["alpha.pdf"] == 2 * 2  # two pages, twice


