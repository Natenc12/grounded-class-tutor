class FakeEmbeddings:
    """Deterministic, free, and LOUD if a test embeds when it should not have.

    `calls` is the assertion surface for convergence: the whole point of checking before ingesting
    is that a second run costs nothing, and the only way to prove "nothing" is that the embedder
    was never touched.
    """

    model_id = "fake-embed-3"

    def __init__(self) -> None:
        self.calls: list[list[str]] = []

    def embed(self, texts):
        texts = list(texts)
        self.calls.append(texts)
        # A distinct but deterministic unit-ish vector per text; content is irrelevant here
        # because no test in this file asserts on ranking.
        return [[float((hash(t) % 97) + 1)] + [0.0] * (EMBEDDING_DIM - 1) for t in texts]


def write_pdf(path: Path, page_texts: list[str]) -> Path:
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=(612, 792))
    for text in page_texts:
        c.drawString(72, 700, text)
        c.showPage()
    c.save()
    path.write_bytes(buf.getvalue())
    return path


